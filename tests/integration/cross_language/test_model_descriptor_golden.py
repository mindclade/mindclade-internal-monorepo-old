def test_python_reproduces_the_go_sealed_canonical_bytes() -> None:
    expected = (FIXTURES / "model_descriptor_v1.bin").read_bytes()
    assert descriptor().canonical_bytes() == expected


def test_python_seals_the_digest_the_go_writer_published() -> None:
    meta = json.loads((FIXTURES / "model_descriptor_v1.json").read_text())
    payload = (FIXTURES / "model_descriptor_v1.bin").read_bytes()
    assert "sha256:" + hashlib.sha256(payload).hexdigest() == meta["canonical_sha256"]
    sealed = dataclasses.replace(descriptor(), descriptor_digest=meta["descriptor_digest"])
    sealed.verify_digest()


def test_golden_descriptor_opens_with_the_declared_document_type() -> None:
    meta = json.loads((FIXTURES / "model_descriptor_v1.json").read_text())
    payload = (FIXTURES / "model_descriptor_v1.bin").read_bytes()
    assert payload.startswith(meta["document_type"].encode() + b"\n")
