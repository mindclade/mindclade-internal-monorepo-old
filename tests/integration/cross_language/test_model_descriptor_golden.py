"""Go and Python must seal `inference-model-descriptor/v1` to the same bytes.

Go writes the descriptor and seals its digest; the Python worker recomputes that
digest before it will serve. If the two encoders drift, every worker rejects
every descriptor the control plane publishes — a total serving outage that no
single-language test can see. The fixture is generated by the Go writer and
checked in, so a change to either side has to update it deliberately.
"""

from __future__ import annotations

import dataclasses
import hashlib
import json
from pathlib import Path

from serving.contracts import CompatibilityClass, ModelDescriptor, ResourceEnvelope

FIXTURES = Path(__file__).resolve().parent / "fixtures"

MODEL_BUNDLE = "sha256:e8bebfc4f9adafe9b232c13f5547eef3bff0f2d3da3dbc6e98d94f69a6061eb4"
ENGINE_BUNDLE = "sha256:d1c4682583ee5ef93432f3c397a87c9921a2465e23f988a95be40a95cc3c89f8"
RESOLVED_CONFIG = "sha256:5ac6d48dedc51f671110b07a531e822128c91cdac44c249a677a45321f64955d"
KERNEL_MANIFEST = "sha256:5b5f5aa2ec370ac18b858b957721bdb22082199eb574e7b60d67648fdefbac3f"
SAFETY_POLICY = "sha256:fce8b57e76301846c42fad20317ea0c94b0ee37bf44d0c41ff15e319d37687b2"

CREATED = 1_800_000_000_000
EXPIRES = CREATED + 86_400_000


