def _compare_surfaces(left_name: str, left: Surface, right_name: str, right: Surface) -> list[str]:
    errors: list[str] = []
    if left.package != right.package:
        errors.append(
            f"package: {left_name} says {left.package!r}, {right_name} says {right.package!r}"
        )
    if left.syntax != right.syntax:
        errors.append(
            f"syntax: {left_name} says {left.syntax!r}, {right_name} says {right.syntax!r}"
        )
    for kind, left_items, right_items in (
        ("message", left.messages, right.messages),
        ("enum", left.enums, right.enums),
        ("service", left.services, right.services),
    ):
        for name in sorted(set(left_items) - set(right_items)):
            errors.append(f"{kind} {name} is in {left_name} but not in {right_name}")
        for name in sorted(set(right_items) - set(left_items)):
            errors.append(f"{kind} {name} is in {right_name} but not in {left_name}")
        for name in sorted(set(left_items) & set(right_items)):
            left_members = left_items[name]
            right_members = right_items[name]
            rendered_left = _render_members(left_members)
            rendered_right = _render_members(right_members)
            if rendered_left != rendered_right:
                errors.append(
                    f"{kind} {name}: {left_name} declares [{', '.join(rendered_left)}] "
                    f"but {right_name} declares [{', '.join(rendered_right)}]"
                )
    return errors


def _render_members(members: Sequence[Member] | Sequence[str]) -> list[str]:
    return sorted(m.render() if isinstance(m, Member) else m for m in members)


