def _read_gitattributes_rules(root: Path) -> set[str]:
    path = root / ".gitattributes"
    if not path.is_file():
        raise VerificationError(".gitattributes is missing; nothing declares generated artifacts")
    patterns: set[str] = set()
    for line in path.read_text(encoding="utf-8").splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        pattern, *attributes = stripped.split()
        if "linguist-generated=true" in attributes:
            patterns.add(pattern)
    return patterns


def check_generated_declarations(root: Path) -> list[str]:
    """Every generated artifact is declared generated, and every declaration has a disposition."""
    declared = _read_gitattributes_rules(root)
    claimed = {rule.pattern for rule in GENERATED_RULES}
    errors = [
        f".gitattributes marks {pattern!r} linguist-generated but "
        f"tools/codegen/verify_generated.py has no disposition for it. Add a GENERATED_RULES "
        f"entry saying whether it is regenerated, must be absent, or is unverifiable and why."
        for pattern in sorted(declared - claimed)
    ]
    errors.extend(
        f"GENERATED_RULES claims {pattern!r} but .gitattributes no longer marks it "
        f"linguist-generated; a generated artifact that stops being declared generated is "
        f"reviewed as source and verified by nothing."
        for pattern in sorted(claimed - declared)
    )
    return errors


def check_absent_artifacts(root: Path) -> list[str]:
    """Bindings that Bazel produces at build time must never be committed.

    `.gitattributes` already declares `protocols/**/*.pb.go` and friends generated, which is a
    rule with no tree behind it: there is no `protocols/gen` by design. Left alone it is a trap —
    the day one of those files is committed it arrives pre-collapsed in review and unverified by
    anything, because the only reason the rule was harmless is that the files did not exist.
    """
    errors: list[str] = []
    for rule in GENERATED_RULES:
        if rule.disposition != ABSENT:
            continue
        prefix, separator, leaf = rule.pattern.partition("/**/")
        if not separator or not leaf:
            # Raised rather than skipped: a pattern this loop cannot walk is a rule that silently
            # stops being enforced, which is the same defect as having no rule.
            raise VerificationError(
                f"GENERATED_RULES pattern {rule.pattern!r} is marked absent but is not of the "
                f"`<directory>/**/<glob>` form this check can walk"
            )
        for path in sorted((root / prefix).rglob(leaf)):
            if path.is_file():
                errors.append(
                    f"{path.relative_to(root).as_posix()} is committed, but {rule.reason}. "
                    f"Delete it and depend on the Bazel target instead."
                )
    return errors


def _proto_sources(root: Path) -> dict[str, Path]:
    base = root / PROTO_ROOT
    return {path.relative_to(base).as_posix(): path for path in sorted(base.rglob("*.proto"))}


def _typescript_bindings(root: Path) -> dict[str, Path]:
    base = root / TS_PROTO_ROOT
    return {path.relative_to(base).as_posix(): path for path in sorted(base.rglob("*_pb.ts"))}


def check_binding_bijection(root: Path) -> list[str]:
    """One `.proto` in, exactly one `_pb.ts` out, and nothing else in the generated tree."""
    protos = _proto_sources(root)
    bindings = _typescript_bindings(root)
    expected = {relpath[: -len(".proto")] + "_pb.ts" for relpath in protos}
    errors = [
        f"{PROTO_ROOT}/{name[: -len('_pb.ts')]}.proto has no generated "
        f"{TS_PROTO_ROOT}/{name}; run `pnpm generate`"
        for name in sorted(expected - set(bindings))
    ]
    errors.extend(
        f"{TS_PROTO_ROOT}/{name} has no source under {PROTO_ROOT}; it is an orphan of a deleted "
        f"or renamed contract and must be removed by `pnpm generate`"
        for name in sorted(set(bindings) - expected)
    )
    generated_root = root / TS_GENERATED_ROOT
    known = {root / TS_OPENAPI_FILE, *bindings.values()}
    errors.extend(
        f"{path.relative_to(root).as_posix()} sits in the generated tree but no generator in "
        f"tools/codegen produces it"
        for path in sorted(generated_root.rglob("*"))
        if path.is_file() and path not in known
    )
    if not (root / TS_OPENAPI_FILE).is_file():
        errors.append(f"{TS_OPENAPI_FILE} is missing; run `pnpm generate`")
    if not (root / OPENAPI_SOURCE).is_file():
        errors.append(f"{OPENAPI_SOURCE} is missing but {TS_OPENAPI_FILE} is generated from it")
    return errors


_EXACT_VERSION = re.compile(r"^\d+\.\d+\.\d+(?:[-+][\w.-]+)?$")


def _pinned_plugin_version(root: Path) -> str:
    """The exact protoc-gen-es version `package.json` pins.

    A range (`^2.14.0`, `~2.14.0`, `latest`) is rejected here rather than stripped down to a
    number. The generator stamps the version it actually ran into every file, so a range makes
    the stamp unverifiable — and stripping the specifier would compare the stamp against a
    version that `pnpm install` is free not to have installed, which is a check that looks like
    it works. The repository pins exactly today; this says so out loud.
    """
    manifest = json.loads((root / "package.json").read_text(encoding="utf-8"))
    for section in ("devDependencies", "dependencies"):
        version = str(manifest.get(section, {}).get(PROTOC_GEN_ES_PACKAGE, ""))
        if not version:
            continue
        if not _EXACT_VERSION.match(version):
            raise VerificationError(
                f"package.json pins {PROTOC_GEN_ES_PACKAGE} as {version!r}, which is a range. "
                f"The generated files record the version that produced them, so verifying them "
                f"needs an exact pin."
            )
        return version
    raise VerificationError(f"package.json does not pin {PROTOC_GEN_ES_PACKAGE}")


def _template_parameter(root: Path) -> str:
    """The `opt:` list protoc-gen-es is invoked with, as it records it in each file's header.

    Scoped to the `- local: protoc-gen-es` entry rather than to the first `opt:` in the file.
    Unscoped, adding any plugin ahead of protoc-gen-es would compare every binding's stamped
    parameter against a different plugin's options and fail the entire tree with a message that
    regeneration cannot satisfy.

    Read as text rather than with PyYAML: this lane runs inside `--static-only`, which is
    documented to have no third-party Python dependencies, and the block is a flat list of
    scalars under a single key.
    """
    text = (root / BUF_TEMPLATE).read_text(encoding="utf-8")
    match = re.search(
        rf"^  - local: {re.escape(PROTOC_GEN_ES_PLUGIN)}\n"
        rf"(?:    (?!opt:)\S.*\n)*"
        rf"    opt:\n(?P<items>(?:      - .*\n)+)",
        text,
        re.MULTILINE,
    )
    if match is None:
        raise VerificationError(
            f"{BUF_TEMPLATE} has no `opt:` list under its `- local: {PROTOC_GEN_ES_PLUGIN}` "
            f"plugin entry, so the parameter stamped into each generated file cannot be checked"
        )
    return ",".join(line.split("- ", 1)[1].strip() for line in match.group("items").splitlines())


def check_generated_bindings(root: Path) -> list[str]:
    """Cross-examine the three witnesses for every generated protobuf binding."""
    protos = _proto_sources(root)
    bindings = _typescript_bindings(root)
    pinned_version = _pinned_plugin_version(root)
    pinned_parameter = _template_parameter(root)
    errors: list[str] = []

    for name, path in bindings.items():
        relpath = f"{TS_PROTO_ROOT}/{name}"
        proto_relpath = name[: -len("_pb.ts")] + ".proto"
        try:
            binding = read_typescript_binding(path.read_text(encoding="utf-8"), relpath)
        except VerificationError as error:
            errors.append(str(error))
            continue

        if binding.plugin_version != pinned_version:
            errors.append(
                f"{relpath} was generated by protoc-gen-es v{binding.plugin_version} but "
                f"package.json pins {PROTOC_GEN_ES_PACKAGE} {pinned_version}; run `pnpm generate`"
            )
        if binding.plugin_parameter != pinned_parameter:
            errors.append(
                f"{relpath} was generated with parameter {binding.plugin_parameter!r} but "
                f"{BUF_TEMPLATE} now specifies {pinned_parameter!r}; run `pnpm generate`"
            )
        if binding.source_file != proto_relpath:
            errors.append(
                f"{relpath} claims to come from {binding.source_file!r} but its path in the "
                f"generated tree mirrors {proto_relpath!r}"
            )
        if binding.descriptor_source_file != proto_relpath:
            errors.append(
                f"{relpath}: the embedded descriptor was compiled from "
                f"{binding.descriptor_source_file!r}, not {proto_relpath!r}"
            )

        errors.extend(
            f"{relpath}: {message}"
            for message in _compare_surfaces(
                "the embedded descriptor",
                binding.descriptor_surface,
                "the emitted TypeScript",
                binding.surface,
            )
        )
        errors.extend(_check_declared_symbols(binding))

        source = protos.get(proto_relpath)
        if source is None:
            continue  # already reported by the bijection check
        try:
            declared = parse_proto_source(
                source.read_text(encoding="utf-8"), f"{PROTO_ROOT}/{proto_relpath}"
            )
        except VerificationError as error:
            errors.append(str(error))
            continue
        errors.extend(
            f"{PROTO_ROOT}/{proto_relpath} vs {relpath}: {message}"
            for message in _compare_surfaces(
                "the .proto source",
                declared,
                "the embedded descriptor",
                binding.descriptor_surface,
            )
        )
    return errors


def _check_declared_symbols(binding: TypeScriptBinding) -> list[str]:
    """The annotations must sit above declarations that actually carry the same names.

    The `@generated from ...` comments are the machine-readable half of the emitted file and the
    descriptor pins them. What they cannot pin on their own is the TypeScript underneath: a
    renamed property with its annotation left intact still type-checks, still lints, and still
    reads as generated. This is the check that catches an edit to the code rather than to its
    documentation.
    """
    errors: list[str] = []
    package = binding.surface.package
    for name, fields in binding.surface.messages.items():
        block = binding.blocks[name]
        symbol = _ts_identifier(name)
        if f'export type {symbol} = Message<"{package}.{name}">' not in block:
            errors.append(
                f"{binding.relpath}: message {name} has no matching "
                f'`export type {symbol} = Message<"{package}.{name}">` declaration'
            )
        if f"export const {symbol}Schema: GenMessage<{symbol}>" not in block:
            errors.append(
                f"{binding.relpath}: message {name} has no matching "
                f"`export const {symbol}Schema: GenMessage<{symbol}>` declaration"
            )
        for member in fields:
            camel = _lower_camel(member.name)
            if not _field_member_pattern(camel).search(block):
                errors.append(
                    f"{binding.relpath}: message {name} declares field {member.name!r} but the "
                    f"emitted TypeScript has no {camel!r} member; the annotation and the code "
                    f"disagree, which regeneration cannot produce"
                )
    for name, values in binding.surface.enums.items():
        block = binding.blocks[name]
        symbol = _ts_identifier(name)
        if f"export enum {symbol} {{" not in block:
            errors.append(
                f"{binding.relpath}: enum {name} has no matching `export enum {symbol}` declaration"
            )
        # protobuf-es drops the SCREAMING_SNAKE prefix derived from the enum's own name, which
        # is why `ERROR_CODE_NOT_FOUND` is emitted as `NOT_FOUND`. Accept either spelling: the
        # point is that the member exists under a name the value actually implies.
        prefix = f"{_upper_snake(name.rsplit('.', 1)[-1])}_"
        for member in values:
            stripped = member.name.removeprefix(prefix)
            pattern = rf"^\s*(?:{re.escape(stripped)}|{re.escape(member.name)}) = "
            if not re.search(pattern, block, re.MULTILINE):
                errors.append(
                    f"{binding.relpath}: enum {name} declares value {member.name!r} but the "
                    f"emitted TypeScript has no {stripped!r} member"
                )
    for name, methods in binding.surface.services.items():
        block = binding.blocks[name]
        if f"export const {name}: GenService<{{" not in block:
            errors.append(
                f"{binding.relpath}: service {name} has no matching "
                f"`export const {name}: GenService<...>` declaration"
            )
        for method in methods:
            camel = _lower_camel(method[:1].lower() + method[1:])
            if not re.search(rf"^\s*{re.escape(camel)}: \{{", block, re.MULTILINE):
                errors.append(
                    f"{binding.relpath}: service {name} declares rpc {method!r} but the emitted "
                    f"TypeScript has no {camel!r} method"
                )
    return errors


_OPENAPI_BANNER = "This file was auto-generated by openapi-typescript."
_OPENAPI_PATH_LINE = re.compile(r"^  (?P<path>/\S*):\s*$")


def _openapi_paths(root: Path) -> list[str]:
    """The keys of the top-level `paths:` mapping, read as text.

    A two-space-indented `/...:` line inside the `paths:` block, which is the only shape the
    contract uses and the only one `buf`/Spectral would accept. Read lexically for the same
    reason as `_template_parameter`: the static lane owns no YAML parser.
    """
    text = (root / OPENAPI_SOURCE).read_text(encoding="utf-8")
    paths: list[str] = []
    inside = False
    for line in text.splitlines():
        if line.startswith("paths:"):
            inside = True
            continue
        if inside:
            if line and not line.startswith((" ", "\t", "#")):
                break
            match = _OPENAPI_PATH_LINE.match(line)
            if match:
                paths.append(match.group("path"))
    return paths


def check_openapi_binding(root: Path) -> list[str]:
    """The generated OpenAPI client exposes exactly the operations the contract declares."""
    target = root / TS_OPENAPI_FILE
    if not target.is_file() or not (root / OPENAPI_SOURCE).is_file():
        return []  # already reported by the bijection check
    text = target.read_text(encoding="utf-8")
    if _OPENAPI_BANNER not in text:
        return [
            f"{TS_OPENAPI_FILE} has no openapi-typescript banner; it was not produced by the "
            f"generator. Run `pnpm generate`."
        ]
    match = re.search(r"export interface paths \{(?P<body>.*?)\n\}", text, re.DOTALL)
    if match is None:
        return [f"{TS_OPENAPI_FILE} has no `export interface paths` block; run `pnpm generate`"]
    emitted = set(re.findall(r'^    "(?P<path>/[^"]*)":', match.group("body"), re.MULTILINE))
    declared = set(_openapi_paths(root))
    errors = [
        f"{OPENAPI_SOURCE} declares path {path!r} but {TS_OPENAPI_FILE} does not expose it; "
        f"run `pnpm generate`"
        for path in sorted(declared - emitted)
    ]
    errors.extend(
        f"{TS_OPENAPI_FILE} exposes path {path!r} that {OPENAPI_SOURCE} no longer declares; "
        f"run `pnpm generate`"
        for path in sorted(emitted - declared)
    )
    return errors


STATIC_CHECKS = (
    ("generated declarations", check_generated_declarations),
    ("build-time bindings absent", check_absent_artifacts),
    ("protobuf binding bijection", check_binding_bijection),
    ("protobuf binding contents", check_generated_bindings),
    ("OpenAPI client contents", check_openapi_binding),
)


def check(root: Path) -> list[str]:
    """The hermetic lane, in the shape `run_architecture_checks.py` expects.

    Wraps each checker so an unreadable witness is reported as a failure. A gate that returns no
    errors because it could not look is the failure mode this file was written against.
    """
    errors: list[str] = []
    for name, checker in STATIC_CHECKS:
        try:
            errors.extend(checker(root))
        except (VerificationError, OSError, ValueError) as error:
            errors.append(f"{name} could not be verified: {error}")
    return errors


