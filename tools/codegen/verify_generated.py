def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--repo", type=Path, default=ROOT)
    parser.add_argument(
        "--mode",
        choices=("static", "regenerate", "all"),
        default="all",
        help="static is hermetic and is what presubmit runs; regenerate needs node_modules",
    )
    parser.add_argument(
        "--repeat",
        action="store_true",
        help="generate twice and compare the passes, proving generation is deterministic",
    )
    args = parser.parse_args(argv)
    root = args.repo.resolve()

    errors: list[str] = []
    if args.mode in ("static", "all"):
        for name, checker in STATIC_CHECKS:
            try:
                found = checker(root)
            except (VerificationError, OSError, ValueError) as error:
                found = [f"{name} could not be verified: {error}"]
            if found:
                errors.extend(f"{name}: {message}" for message in found)
            else:
                print(f"PASS {name}")
    if args.mode in ("regenerate", "all"):
        try:
            found = check_regenerated(root, repeat=args.repeat)
        except (VerificationError, OSError, subprocess.CalledProcessError) as error:
            found = [f"regeneration failed: {error}"]
        if found:
            errors.extend(f"regenerated output: {message}" for message in found)
        else:
            print("PASS regenerated output")

    for message in errors:
        print(message, file=sys.stderr)
    if errors:
        print(
            f"generated-artifact verification failed with {len(errors)} finding(s)", file=sys.stderr
        )
        return 1
    print("generated artifacts match protocols/")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
