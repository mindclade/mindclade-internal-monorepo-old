# The shape the three witnesses are reduced to
# ---------------------------------------------------------------------------------------


@dataclass(frozen=True)
class Member:
    """A message field or an enum value: a name and the number it is bound to."""

    name: str
    number: int

    def render(self) -> str:
        return f"{self.name}={self.number}"


@dataclass(frozen=True)
class Surface:
    """The declared contract of one `.proto` file, however it was witnessed.

    Deliberately names and numbers only. Types are left out because the three witnesses spell
    them differently — `.proto` writes `mindclade.common.v1.PageRequest`, the descriptor writes
    `.mindclade.common.v1.PageRequest`, TypeScript writes `PageRequest` — and reconciling three
    spellings is how a comparison acquires the special cases that eventually make it fail open.
    Names and numbers are the wire contract, spelled identically by all three.
    """

    package: str
    syntax: str
    messages: dict[str, tuple[Member, ...]]
    enums: dict[str, tuple[Member, ...]]
    services: dict[str, tuple[str, ...]]


def _empty_surface(package: str = "", syntax: str = "") -> Surface:
    return Surface(package=package, syntax=syntax, messages={}, enums={}, services={})


# ---------------------------------------------------------------------------------------
# W2 — the descriptor embedded in the generated TypeScript
# ---------------------------------------------------------------------------------------


def _decode_message_type(
    buf: bytes, prefix: str, enums: dict[str, tuple[Member, ...]]
) -> dict[str, tuple[Member, ...]]:
    """Flatten one `DescriptorProto` and its nesting into `{dotted name: fields}`.

    Nested enums are accumulated into `enums` under the same dotted naming, because a message
    that declares an enum inside itself is one declaration in the descriptor and two exported
    symbols in TypeScript.

    Map fields expand into a synthetic nested `XxxEntry` message carrying `options.map_entry`.
    protoc-gen-es does not emit a declaration for those, so counting them here would report a
    message missing from TypeScript on every `map<...>` field in the tree.
    """
    name = ""
    fields: list[Member] = []
    nested: list[bytes] = []
    nested_enums: list[bytes] = []
    is_map_entry = False
    for number, value in _iter_wire(buf):
        if number == 1:  # DescriptorProto.name
            name = _as_str(value, "message name")
        elif number == 2:  # DescriptorProto.field
            field_name = ""
            field_number = 0
            for fnum, fval in _iter_wire(_as_bytes(value, "field")):
                if fnum == 1:
                    field_name = _as_str(fval, "field name")
                elif fnum == 3:
                    field_number = _as_int(fval, "field number")
            fields.append(Member(field_name, field_number))
        elif number == 3:  # DescriptorProto.nested_type
            nested.append(_as_bytes(value, "nested type"))
        elif number == 4:  # DescriptorProto.enum_type
            nested_enums.append(_as_bytes(value, "nested enum type"))
        elif number == 7:  # DescriptorProto.options
            for onum, oval in _iter_wire(_as_bytes(value, "message options")):
                if onum == 7:  # MessageOptions.map_entry
                    is_map_entry = bool(_as_int(oval, "map_entry"))
    if not name:
        raise VerificationError("descriptor contains a message with no name")
    if is_map_entry:
        return {}
    dotted = f"{prefix}{name}"
    out: dict[str, tuple[Member, ...]] = {dotted: tuple(fields)}
    for child in nested_enums:
        enum_name, enum_values = _decode_enum_type(child, f"{dotted}.")
        enums[enum_name] = enum_values
    for child in nested:
        out.update(_decode_message_type(child, f"{dotted}.", enums))
    return out


def _decode_enum_type(buf: bytes, prefix: str) -> tuple[str, tuple[Member, ...]]:
    name = ""
    values: list[Member] = []
    for number, value in _iter_wire(buf):
        if number == 1:  # EnumDescriptorProto.name
            name = _as_str(value, "enum name")
        elif number == 2:  # EnumDescriptorProto.value
            value_name = ""
            value_number = 0
            for vnum, vval in _iter_wire(_as_bytes(value, "enum value")):
                if vnum == 1:
                    value_name = _as_str(vval, "enum value name")
                elif vnum == 2:
                    value_number = _as_int(vval, "enum value number")
            values.append(Member(value_name, value_number))
    if not name:
        raise VerificationError("descriptor contains an enum with no name")
    return f"{prefix}{name}", tuple(values)


def _decode_service(buf: bytes) -> tuple[str, tuple[str, ...]]:
    name = ""
    methods: list[str] = []
    for number, value in _iter_wire(buf):
        if number == 1:  # ServiceDescriptorProto.name
            name = _as_str(value, "service name")
        elif number == 2:  # ServiceDescriptorProto.method
            for mnum, mval in _iter_wire(_as_bytes(value, "method")):
                if mnum == 1:
                    methods.append(_as_str(mval, "method name"))
    if not name:
        raise VerificationError("descriptor contains a service with no name")
    return name, tuple(methods)


def decode_file_descriptor(blob: bytes) -> tuple[str, Surface]:
    """Return `(declared source file name, surface)` for a serialized `FileDescriptorProto`."""
    file_name = ""
    package = ""
    syntax = "proto2"  # descriptor.proto omits the field for proto2, which is its default
    messages: dict[str, tuple[Member, ...]] = {}
    enums: dict[str, tuple[Member, ...]] = {}
    services: dict[str, tuple[str, ...]] = {}
    for number, value in _iter_wire(blob):
        if number == 1:  # FileDescriptorProto.name
            file_name = _as_str(value, "file name")
        elif number == 2:  # FileDescriptorProto.package
            package = _as_str(value, "package")
        elif number == 4:  # FileDescriptorProto.message_type
            messages.update(_decode_message_type(_as_bytes(value, "message type"), "", enums))
        elif number == 5:  # FileDescriptorProto.enum_type
            enum_name, enum_values = _decode_enum_type(_as_bytes(value, "enum type"), "")
            enums[enum_name] = enum_values
        elif number == 6:  # FileDescriptorProto.service
            service_name, methods = _decode_service(_as_bytes(value, "service"))
            services[service_name] = methods
        elif number == 12:  # FileDescriptorProto.syntax
            syntax = _as_str(value, "syntax")
    return file_name, Surface(
        package=package, syntax=syntax, messages=messages, enums=enums, services=services
    )


# ---------------------------------------------------------------------------------------
# W1 — the `.proto` source
# ---------------------------------------------------------------------------------------

_PROTO_TOKEN = re.compile(
    r"""
    "(?:[^"\\\n]|\\.)*"        # string literal
  | '(?:[^'\\\n]|\\.)*'
  | \.?[A-Za-z_][A-Za-z0-9_.]* # identifier, possibly dotted or fully qualified
  | -?\d[\w.+-]*               # number, including hex and floats
  | [{}()\[\]<>,;=]            # punctuation the grammar depends on
  | \S                         # anything else, so an unknown character is a token and not silence
    """,
    re.VERBOSE,
)

_LINE_COMMENT = re.compile(r"//[^\n]*")
_BLOCK_COMMENT = re.compile(r"/\*.*?\*/", re.DOTALL)

# Statements that declare nothing this gate compares, but are valid and must not be errors.
_PROTO_SKIPPED_STATEMENTS = frozenset({"option", "reserved", "extensions", "import"})
_PROTO_FIELD_LABELS = frozenset({"repeated", "optional", "required"})


class _ProtoParser:
    """A proto2/proto3 statement reader that extracts declared names and numbers.

    Fail-closed on purpose: an unrecognized statement raises rather than being skipped. A parser
    that shrugs at what it does not understand degrades into one that verifies a subset nobody
    can name, and the first `.proto` construct it silently drops is the first place drift can
    live. The cost is that a genuinely new construct requires an edit here, which is a bounded,
    visible cost with a message that says exactly what to add.
    """

    def __init__(self, text: str, relpath: str) -> None:
        stripped = _BLOCK_COMMENT.sub(" ", text)
        stripped = _LINE_COMMENT.sub(" ", stripped)
        self._tokens = _PROTO_TOKEN.findall(stripped)
        self._pos = 0
        self._relpath = relpath

    def _fail(self, message: str) -> VerificationError:
        near = " ".join(self._tokens[max(0, self._pos - 3) : self._pos + 3])
        return VerificationError(f"{self._relpath}: {message} (near: {near!r})")

    def _peek(self) -> str | None:
        return self._tokens[self._pos] if self._pos < len(self._tokens) else None

    def _next(self) -> str:
        token = self._peek()
        if token is None:
            raise self._fail("unexpected end of file")
        self._pos += 1
        return token

    def _expect(self, token: str) -> None:
        found = self._next()
        if found != token:
            raise self._fail(f"expected {token!r}, found {found!r}")

    def _skip_to_semicolon(self) -> None:
        """Consume a statement, following any brace/bracket groups it contains."""
        depth = 0
        while True:
            token = self._next()
            if token in "{[(":
                depth += 1
            elif token in "}])":
                depth -= 1
                if depth <= 0 and token == "}":
                    # An aggregate option body may end the statement without a semicolon.
                    if self._peek() == ";":
                        self._next()
                    return
            elif token == ";" and depth == 0:
                return

    def _skip_field_options(self) -> None:
        if self._peek() != "[":
            return
        depth = 0
        while True:
            token = self._next()
            if token == "[":
                depth += 1
            elif token == "]":
                depth -= 1
                if depth == 0:
                    return

    def _read_number(self) -> int:
        token = self._next()
        try:
            return int(token, 0)
        except ValueError as error:
            raise self._fail(f"expected a field number, found {token!r}") from error

    def parse(self) -> Surface:
        package = ""
        syntax = "proto2"
        messages: dict[str, tuple[Member, ...]] = {}
        enums: dict[str, tuple[Member, ...]] = {}
        services: dict[str, tuple[str, ...]] = {}
        while (token := self._peek()) is not None:
            self._next()
            if token == ";":
                continue
            if token in ("syntax", "edition"):
                self._expect("=")
                syntax = self._next().strip("\"'")
                self._expect(";")
            elif token == "package":
                package = self._next()
                self._expect(";")
            elif token in _PROTO_SKIPPED_STATEMENTS:
                self._skip_to_semicolon()
            elif token == "message":
                messages.update(self._parse_message("", enums))
            elif token == "enum":
                name, values = self._parse_enum("")
                enums[name] = values
            elif token == "service":
                name, methods = self._parse_service()
                services[name] = methods
            elif token == "extend":
                self._next()
                self._skip_to_semicolon()
            else:
                raise self._fail(f"unsupported top-level statement {token!r}")
        return Surface(
            package=package, syntax=syntax, messages=messages, enums=enums, services=services
        )

    def _parse_message(
        self, prefix: str, enums: dict[str, tuple[Member, ...]]
    ) -> dict[str, tuple[Member, ...]]:
        name = self._next()
        dotted = f"{prefix}{name}"
        self._expect("{")
        fields: list[Member] = []
        out: dict[str, tuple[Member, ...]] = {}
        while (token := self._next()) != "}":
            if token == ";":
                continue
            if token in _PROTO_SKIPPED_STATEMENTS:
                self._skip_to_semicolon()
            elif token == "message":
                out.update(self._parse_message(f"{dotted}.", enums))
            elif token == "enum":
                enum_name, values = self._parse_enum(f"{dotted}.")
                enums[enum_name] = values
            elif token == "extend":
                self._next()
                self._skip_to_semicolon()
            elif token == "oneof":
                self._next()
                self._expect("{")
                while (inner := self._next()) != "}":
                    if inner == ";":
                        continue
                    if inner == "option":
                        self._skip_to_semicolon()
                        continue
                    # Inside a oneof every member is `<type> <name> = <n>;`.
                    fields.append(self._parse_field_tail())
            elif token == "map":
                self._expect("<")
                while self._next() != ">":
                    continue
                fields.append(self._parse_field_tail())
            elif token == "group":
                raise self._fail("proto2 groups are not supported by this checker")
            elif token in _PROTO_FIELD_LABELS:
                self._next()  # the type
                fields.append(self._parse_field_tail())
            else:
                # `token` was the type; the name follows.
                fields.append(self._parse_field_tail())
        out[dotted] = tuple(fields)
        return out

    def _parse_field_tail(self) -> Member:
        """Read `<name> = <number> [options];`, with the type already consumed."""
        name = self._next()
        self._expect("=")
        number = self._read_number()
        self._skip_field_options()
        self._expect(";")
        return Member(name, number)

    def _parse_enum(self, prefix: str) -> tuple[str, tuple[Member, ...]]:
        name = self._next()
        self._expect("{")
        values: list[Member] = []
        while (token := self._next()) != "}":
            if token == ";":
                continue
            if token in _PROTO_SKIPPED_STATEMENTS:
                self._skip_to_semicolon()
                continue
            self._expect("=")
            number = self._read_number()
            self._skip_field_options()
            self._expect(";")
            values.append(Member(token, number))
        return f"{prefix}{name}", tuple(values)

    def _parse_service(self) -> tuple[str, tuple[str, ...]]:
        name = self._next()
        self._expect("{")
        methods: list[str] = []
        while (token := self._next()) != "}":
            if token == ";":
                continue
            if token in _PROTO_SKIPPED_STATEMENTS:
                self._skip_to_semicolon()
                continue
            if token != "rpc":
                raise self._fail(f"unsupported statement {token!r} inside a service")
            methods.append(self._next())
            # `( [stream] Type ) returns ( [stream] Type )` then either `;` or an options body.
            for _ in range(2):
                while self._next() != ")":
                    continue
            if self._peek() == "{":
                self._skip_to_semicolon()
            else:
                self._expect(";")
        return name, tuple(methods)


def parse_proto_source(text: str, relpath: str) -> Surface:
    return _ProtoParser(text, relpath).parse()


