def _generate_into(root: Path, destination: Path) -> None:
    """Run the pinned generators with `destination` as their output prefix."""
    bin_dir = root / "node_modules" / ".bin"
    buf = bin_dir / "buf"
    openapi = bin_dir / "openapi-typescript"
    for tool in (buf, openapi):
        if not tool.exists():
            raise VerificationError(
                f"{tool.relative_to(root).as_posix()} is missing. Regeneration needs the pinned "
                f"Node toolchain: `tools/dev/nixw develop .#default --command pnpm install "
                f"--frozen-lockfile`, then rerun."
            )
    # `pnpm exec` re-runs `pnpm install` before the command, which both mutates the tree and
    # fails on ignored build scripts. Invoke the pinned binaries directly and put `.bin` on PATH
    # so `buf` can find `protoc-gen-es`, which is how buf resolves a `local:` plugin.
    env = dict(os.environ)
    env["PATH"] = os.pathsep.join([str(bin_dir), env.get("PATH", "")])
    subprocess.run(
        [str(buf), "generate", "protocols", "--template", BUF_TEMPLATE, "-o", str(destination)],
        cwd=root,
        env=env,
        check=True,
    )
    subprocess.run(
        [str(openapi), OPENAPI_SOURCE, "-o", str(destination / TS_OPENAPI_FILE)],
        cwd=root,
        env=env,
        check=True,
    )


def _tree(base: Path, prefix: str) -> dict[str, bytes]:
    """Map repository-relative path to content, so a finding names the file a reader can open."""
    return {
        f"{prefix}/{path.relative_to(base).as_posix()}": path.read_bytes()
        for path in sorted(base.rglob("*"))
        if path.is_file()
    }


def _diff(relpath: str, committed: bytes, regenerated: bytes) -> str:
    """One finding, rendered as a bounded unified diff of committed against generated."""
    headline = (
        f"{relpath}: committed content differs from regenerated output "
        f"(a/ is committed, b/ is generated):"
    )
    try:
        committed_lines = committed.decode("utf-8").splitlines(keepends=True)
        regenerated_lines = regenerated.decode("utf-8").splitlines(keepends=True)
    except UnicodeDecodeError:
        return f"{relpath}: committed binary content differs from regenerated output"
    lines = list(
        difflib.unified_diff(
            committed_lines,
            regenerated_lines,
            fromfile=f"a/{relpath}",
            tofile=f"b/{relpath}",
            n=2,
        )
    )
    rendered = [f"  {line.rstrip()}" for line in lines[:MAX_DIFF_LINES]]
    if len(lines) > MAX_DIFF_LINES:
        rendered.append(f"  ... {len(lines) - MAX_DIFF_LINES} further diff line(s) suppressed")
    return "\n".join([headline, *rendered])


def compare_trees(committed: dict[str, bytes], regenerated: dict[str, bytes]) -> list[str]:
    """Report every way the committed tree differs from freshly generated output.

    Each finding is one string, multi-line where it carries a diff, so the failure count at the
    end names files rather than diff lines.
    """
    errors: list[str] = [
        f"{relpath}: generated but not committed; run `pnpm generate`"
        for relpath in sorted(set(regenerated) - set(committed))
    ]
    errors.extend(
        f"{relpath}: committed but no generator produces it; run `pnpm generate`"
        for relpath in sorted(set(committed) - set(regenerated))
    )
    differing = [
        relpath
        for relpath in sorted(set(committed) & set(regenerated))
        if committed[relpath] != regenerated[relpath]
    ]
    errors.extend(
        _diff(relpath, committed[relpath], regenerated[relpath])
        for relpath in differing[:MAX_DIFF_FILES]
    )
    if len(differing) > MAX_DIFF_FILES:
        errors.append(
            f"... and {len(differing) - MAX_DIFF_FILES} further file(s) differ; "
            f"run `pnpm generate` and review the whole diff"
        )
    return errors


def check_regenerated(root: Path, *, repeat: bool = False) -> list[str]:
    """Regenerate into a temporary tree and byte-compare, never touching the working tree."""
    with tempfile.TemporaryDirectory(prefix="mindclade-verify-generated-") as temporary:
        first = Path(temporary) / "first"
        first.mkdir()
        _generate_into(root, first)
        regenerated = _tree(first / TS_GENERATED_ROOT, TS_GENERATED_ROOT)
        errors = compare_trees(_tree(root / TS_GENERATED_ROOT, TS_GENERATED_ROOT), regenerated)
        if repeat:
            second = Path(temporary) / "second"
            second.mkdir()
            _generate_into(root, second)
            repeated = _tree(second / TS_GENERATED_ROOT, TS_GENERATED_ROOT)
            # The union, not the second pass. Iterating only what the second pass emitted would
            # report a generator that drops an output on some runs as perfectly stable, which is
            # the exact nondeterminism this flag exists to rule out before trusting the bytes.
            for relpath in sorted(set(regenerated) | set(repeated)):
                if regenerated.get(relpath) != repeated.get(relpath):
                    errors.append(
                        f"{relpath}: two generation passes over identical inputs disagree, so "
                        f"byte comparison cannot gate this artifact"
                    )
    return errors


