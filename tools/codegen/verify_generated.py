"""The drift gate that makes `protocols/` the wire authority rather than a claim.

`protocols/` is documented as the source of truth for every cross-process contract, and
`.gitattributes` marks the artifacts emitted from it `linguist-generated=true` so they collapse
in review. Both statements were unenforced: nothing compared a committed artifact against what
its source would produce today, so a hand-edit of `sdk/typescript/src/generated/**` or an
un-regenerated `.proto` change would reach `main` reviewed by nobody — the generated files are
exactly the ones a reviewer is told to skip.

Two lanes, because the two useful properties have different costs.

`--mode regenerate` is the authority. It runs the real pinned generators into a temporary tree
and byte-compares against what is committed. It cannot be satisfied by anything except output
the generator actually produces, and it needs `node_modules` (`pnpm install --frozen-lockfile`).

`--mode static` is hermetic: standard library only, no subprocesses, no network, no
`node_modules`. `run_architecture_checks.py` calls `check()`, which is this lane, so drift fails
`pipeline.py --static-only` on every pull request. It cannot byte-compare, so instead it cross-
examines three independent witnesses to the same contract:

    W1  the `.proto` source           parsed from `protocols/proto/**`
    W2  the embedded file descriptor  the base64 `FileDescriptorProto` that protoc-gen-es bakes
                                      into `fileDesc("...")` in every `_pb.ts`
    W3  the emitted TypeScript        the `@generated from ...` annotations and the declarations
                                      and property names they sit above

W2 is the load-bearing one. It is a compiled artifact of the `.proto`, so it is the record of
what the generator actually saw, and it is not something anyone edits by hand to match a lie
told in W1 or W3. Editing a field name in a `_pb.ts` contradicts W2. Editing a `.proto` without
regenerating contradicts W2. Agreement across all three is what regeneration would produce.

DETERMINISM AND HERMETICITY. Byte comparison is only a gate if identical inputs give identical
bytes, so the two things that usually make such a gate flap are handled explicitly rather than
hoped about:

  * Absolute paths. Generation runs with `buf generate -o <tmp>`, which prefixes the output
    directory without entering the emitted content. Verified: a temp-tree generation is
    byte-identical to the committed tree, so no path normalization is needed and none is done —
    normalizing anyway would hide a real regression if a future plugin started embedding paths.
  * Timestamps. Neither protoc-gen-es nor openapi-typescript emits one. Nothing is stripped, for
    the same reason.
  * Tool versions. protoc-gen-es DOES stamp `@generated by protoc-gen-es v2.14.0` into every
    file. That is deliberately NOT normalized away: the version is pinned by `pnpm-lock.yaml`,
    so it is an input like any other, and a bump that is not accompanied by regenerated output
    is precisely the drift this gate exists to catch. The static lane checks the stamp against
    the pinned version in `package.json` for the same reason.
  * The proprietary licence header. It survives regeneration without any help from this tool:
    protoc-gen-es carries a `.proto` file's leading detached comments into its output, and every
    `.proto` here opens with the header. `check_license_headers.py` skips the generated tree
    (`SKIP_PREFIXES`), so the header is not re-inserted afterwards either. `api.ts` has no
    header because openapi-typescript has no equivalent behavior and its YAML source's comments
    are not carried; that asymmetry is generator behavior, not drift.
  * `clean: true` in `protocols/buf.gen.yaml`. Under `-o <tmp>` it cleans the temp prefix, so
    verification never mutates the working tree. This is the difference from
    `generate_typescript_sdk.py --check`, which regenerates in place and compares digests before
    and after — that leaves the tree rewritten whether it passes or fails.

COVERAGE IS ITSELF GATED. `GENERATED_RULES` below claims every `linguist-generated=true` pattern
in `.gitattributes` and states what this tool does about it. A new rule that nothing here claims
is an error, not a silent gap: the failure mode this whole file exists to prevent is a generated
artifact that no gate looks at, and the second one of those would otherwise arrive unannounced.

    python3 tools/codegen/verify_generated.py                  # static + regenerate
    python3 tools/codegen/verify_generated.py --mode static    # hermetic, what presubmit runs
    python3 tools/codegen/verify_generated.py --repeat         # also prove generation is stable
"""

