class VerificationError(Exception):
    """A witness could not be read at all, which is a failure and never a skip."""


# ---------------------------------------------------------------------------------------
# Protobuf wire decoding
# ---------------------------------------------------------------------------------------
# Enough of the wire format to read a `FileDescriptorProto`, in the standard library, because
# the static lane must not acquire a `protobuf` dependency to run in `--static-only`. Field
# numbers below are from `descriptor.proto` and are part of protobuf's compatibility guarantee.

_WIRE_VARINT = 0
_WIRE_I64 = 1
_WIRE_LEN = 2
_WIRE_SGROUP = 3
_WIRE_EGROUP = 4
_WIRE_I32 = 5


def _read_varint(buf: bytes, pos: int) -> tuple[int, int]:
    result = 0
    shift = 0
    while True:
        if pos >= len(buf):
            raise VerificationError("truncated varint")
        if shift > 63:
            raise VerificationError("varint wider than 64 bits")
        byte = buf[pos]
        pos += 1
        result |= (byte & 0x7F) << shift
        if not byte & 0x80:
            return result, pos
        shift += 7


def _iter_wire(buf: bytes) -> Iterator[tuple[int, bytes | int]]:
    """Yield `(field_number, value)` for one message; bytes for length-delimited, int otherwise."""
    pos = 0
    while pos < len(buf):
        tag, pos = _read_varint(buf, pos)
        number, wire = tag >> 3, tag & 0x7
        if number == 0:
            raise VerificationError("field number 0 is not valid")
        if wire == _WIRE_VARINT:
            value, pos = _read_varint(buf, pos)
            yield number, value
        elif wire == _WIRE_I64:
            yield number, int.from_bytes(buf[pos : pos + 8], "little")
            pos += 8
        elif wire == _WIRE_I32:
            yield number, int.from_bytes(buf[pos : pos + 4], "little")
            pos += 4
        elif wire == _WIRE_LEN:
            length, pos = _read_varint(buf, pos)
            end = pos + length
            if end > len(buf):
                raise VerificationError("length-delimited field runs past the end of the message")
            yield number, buf[pos:end]
            pos = end
        elif wire in (_WIRE_SGROUP, _WIRE_EGROUP):
            raise VerificationError("groups are not supported and proto3 cannot produce them")
        else:
            raise VerificationError(f"unknown wire type {wire}")


def _as_bytes(value: bytes | int, what: str) -> bytes:
    if not isinstance(value, bytes):
        raise VerificationError(f"expected a length-delimited {what}")
    return value


def _as_str(value: bytes | int, what: str) -> str:
    return _as_bytes(value, what).decode("utf-8")


def _as_int(value: bytes | int, what: str) -> int:
    if isinstance(value, bytes):
        raise VerificationError(f"expected a varint {what}")
    return value


