def test_absent_lockfile_is_an_error_not_a_pass(tree: Path) -> None:
    (tree / "MODULE.bazel.lock").unlink()
    errors = _errors(tree)
    assert "MODULE.bazel.lock is missing" in errors
    assert freshness.BAZEL_REPIN_COMMAND in errors


def test_unparseable_lockfile_is_an_error_not_a_pass(tree: Path) -> None:
    (tree / "MODULE.bazel.lock").write_text('{"lockFileVersion": 26,', encoding="utf-8")
    assert "MODULE.bazel.lock is not valid JSON" in _errors(tree)


def test_unreadable_lockfile_is_an_error_not_a_pass(tree: Path) -> None:
    """A directory where the lock should be: `is_file` is false, so it reads as absent."""
    (tree / "MODULE.bazel.lock").unlink()
    (tree / "MODULE.bazel.lock").mkdir()
    assert "MODULE.bazel.lock is missing" in _errors(tree)


def test_undecodable_lockfile_is_an_error_not_a_pass(tree: Path) -> None:
    (tree / "MODULE.bazel.lock").write_bytes(b"\xff\xfe\x00binary")
    assert "MODULE.bazel.lock could not be read" in _errors(tree)


def test_an_unknown_lock_format_version_is_an_error_not_a_pass(tree: Path) -> None:
    """A layout this parser has not been read against verifies nothing, so it must not pass."""
    text = (tree / "MODULE.bazel.lock").read_text(encoding="utf-8")
    (tree / "MODULE.bazel.lock").write_text(
        text.replace('"lockFileVersion": 26', '"lockFileVersion": 99'), encoding="utf-8"
    )
    errors = _errors(tree)
    assert "lockFileVersion 99" in errors
    assert "KNOWN_LOCK_FILE_VERSIONS" in errors


def test_a_lockfile_recording_no_file_inputs_is_an_error_not_a_pass(tree: Path) -> None:
    """Verifying an empty set is how a gate prints PASS forever."""
    (tree / "MODULE.bazel.lock").write_text(_lock(["ENV:CARGO_BAZEL_REPIN \\0"]), encoding="utf-8")
    assert "records no main-repository file inputs" in _errors(tree)


def test_a_lockfile_without_the_crate_extension_is_an_error_not_a_pass(tree: Path) -> None:
    document = json.loads((tree / "MODULE.bazel.lock").read_text(encoding="utf-8"))
    document["moduleExtensions"]["@@rules_python+//python/uv:uv.bzl%uv"] = document[
        "moduleExtensions"
    ].pop(CRATE_EXTENSION)
    (tree / "MODULE.bazel.lock").write_text(json.dumps(document), encoding="utf-8")
    assert "records no //crate_universe:extensions.bzl%crate extension" in _errors(tree)


def test_a_malformed_recorded_inputs_block_is_an_error_not_a_pass(tree: Path) -> None:
    document = json.loads((tree / "MODULE.bazel.lock").read_text(encoding="utf-8"))
    document["moduleExtensions"][CRATE_EXTENSION]["general"]["recordedInputs"] = 17
    (tree / "MODULE.bazel.lock").write_text(json.dumps(document), encoding="utf-8")
    assert "malformed recordedInputs" in _errors(tree)


def test_a_recorded_input_that_left_the_tree_is_reported(tree: Path) -> None:
    (tree / "libs/rust/faults/Cargo.toml").unlink()
    assert "recorded as an input of" in _errors(tree)
    assert "absent from the tree" in _errors(tree)


def test_a_malformed_go_sum_line_is_an_error_not_a_pass(tree: Path) -> None:
    (tree / "go.sum").write_text(GO_SUM + "this line has too few fields\n", encoding="utf-8")
    assert "malformed go.sum line" in _errors(tree)


def test_an_absent_go_sum_with_requirements_is_reported(tree: Path) -> None:
    (tree / "go.sum").unlink()
    assert "go.sum is missing while go.mod requires 3 module(s)" in _errors(tree)


def test_an_absent_go_sum_with_no_requirements_is_fine(tree: Path) -> None:
    """sdk/go is exactly this shape today: no requires, an empty go.sum, nothing to authenticate."""
    (tree / "sdk/go/go.sum").unlink()
    assert freshness.check(tree) == []


def test_a_missing_go_mod_is_an_error_not_a_pass(tree: Path) -> None:
    (tree / "sdk/go/go.mod").unlink()
    assert "sdk/go/go.mod is missing" in _errors(tree)


def test_an_unclosed_require_block_is_an_error_not_a_pass(tree: Path) -> None:
    (tree / "go.mod").write_text("module m\n\nrequire (\n\tfoo v1.0.0\n", encoding="utf-8")
    assert "a require block is never closed" in _errors(tree)


def test_a_locally_replaced_module_needs_no_checksum(tree: Path) -> None:
    """A replacement pointing at a directory has no module zip, so demanding a hash would misfire."""
    (tree / "go.mod").write_text(
        GO_MOD + "\nreplace connectrpc.com/connect => ./vendor/connect\n", encoding="utf-8"
    )
    (tree / "go.sum").write_text(
        GO_SUM.replace("connectrpc.com/connect v1.18.1/go.mod h1:bbb=\n", ""), encoding="utf-8"
    )
    assert freshness.check(tree) == []


def test_a_replace_block_is_parsed_as_well_as_a_replace_line(tree: Path) -> None:
    (tree / "go.mod").write_text(
        GO_MOD + "\nreplace (\n\tconnectrpc.com/connect => ../connect\n)\n", encoding="utf-8"
    )
    (tree / "go.sum").write_text(
        GO_SUM.replace("connectrpc.com/connect v1.18.1/go.mod h1:bbb=\n", ""), encoding="utf-8"
    )
    assert freshness.check(tree) == []


