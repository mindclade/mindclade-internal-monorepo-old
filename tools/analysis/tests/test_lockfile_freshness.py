def test_the_real_repository_is_fresh() -> None:
    """The committed tree must satisfy its own gate; otherwise the branch is the defect."""
    assert freshness.check(ROOT) == []


def test_the_check_path_never_shells_out(tree: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    """CI must never regenerate a lockfile. The check path therefore runs no subprocess at all.

    Asserted rather than assumed, because the failure it prevents is silent: a check that quietly
    repinned would turn the fail-closed `--lockfile_mode=error` contract into
    `--lockfile_mode=update` with extra steps, and the committed authority would become whatever
    resolution CI happened to reach.
    """

    def forbidden(*args: object, **kwargs: object) -> None:
        raise AssertionError("the check path must not run a subprocess")

    monkeypatch.setattr(freshness.subprocess, "run", forbidden)
    (tree / "Cargo.lock").write_text("# edited\n", encoding="utf-8")
    assert freshness.check(tree)
    assert freshness.main(["--root", str(tree)]) == 1


def test_fix_runs_the_sanctioned_command_and_re_checks(
    tree: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    """`--fix` regenerates, then decides on the digests -- never on the command's exit status."""
    (tree / "Cargo.lock").write_text("# edited\n", encoding="utf-8")
    invoked: list[list[str]] = []

    class Result:
        # Exit code 0 from a command that repaired nothing: precisely the shape that let three
        # agents report a green Bazel run off the status line while the log said otherwise.
        returncode = 0

    def fake_run(argv: list[str], **kwargs: object) -> Result:
        invoked.append(argv)
        return Result()

    monkeypatch.setattr(freshness.subprocess, "run", fake_run)
    assert freshness.main(["--fix", "--root", str(tree)]) == 1
    assert invoked == [freshness.BAZEL_REPIN_COMMAND.split()]
    assert "mod deps" in " ".join(invoked[0])
    assert "did not resolve the drift" in capsys.readouterr().err


def test_fix_reports_success_only_when_the_digests_agree(
    tree: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    original = (tree / "Cargo.lock").read_text(encoding="utf-8")
    (tree / "Cargo.lock").write_text("# edited\n", encoding="utf-8")

    class Result:
        # The opposite trap: a non-zero status from a command that did in fact repair the tree.
        returncode = 3

    def fake_run(argv: list[str], **kwargs: object) -> Result:
        (tree / "Cargo.lock").write_text(original, encoding="utf-8")
        return Result()

    monkeypatch.setattr(freshness.subprocess, "run", fake_run)
    assert freshness.main(["--fix", "--root", str(tree)]) == 0


def test_fix_regenerates_nothing_when_the_tree_is_already_fresh(
    tree: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    def forbidden(*args: object, **kwargs: object) -> None:
        raise AssertionError("--fix must not regenerate a lockfile that is already fresh")

    monkeypatch.setattr(freshness.subprocess, "run", forbidden)
    assert freshness.main(["--fix", "--root", str(tree)]) == 0


def test_the_checker_needs_no_third_party_import() -> None:
    """The static lane is stdlib-only; an added dependency would move this gate out of it."""
    source = (ANALYSIS / "check_lockfile_freshness.py").read_text(encoding="utf-8")
    imported = {
        line.split()[1].split(".")[0]
        for line in source.splitlines()
        if line.startswith("import ") or line.startswith("from ")
    }
    assert imported <= set(sys.stdlib_module_names) | {"__future__"}
