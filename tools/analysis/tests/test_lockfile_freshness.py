"""A lockfile freshness gate is only worth its runtime if some input makes it fail.

Every case below names one corruption and pins the message that reports it. The three that
reproduce live defects are marked as such: PR #141's `Cargo.lock` edit, the added workspace
member, and the bumped `go.mod` requirement. Each of those returned exit code 0 from `bazelw`
while the log said the build did not complete, which is why they are asserted here on the message
rather than anywhere on a process status.

The guard cases matter as much as the drift cases. An absent, unreadable, or unparseable lockfile
has no digests to compare, and the one outcome that must never follow from "there was nothing to
compare" is a pass -- that is the exact fail-open shape the falsifiability review found ten
instances of. So a missing lock, a truncated lock, an unknown `lockFileVersion`, an extension map
with no file inputs, and a malformed `go.sum` line are each asserted to be reported errors.
"""

from __future__ import annotations

import hashlib
import importlib.util
import json
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[3]
ANALYSIS = ROOT / "tools/analysis"

if str(ANALYSIS) not in sys.path:
    sys.path.insert(0, str(ANALYSIS))


def load(name: str, path: Path):
    spec = importlib.util.spec_from_file_location(name, path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"unable to load {path}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


freshness = load("check_lockfile_freshness", ANALYSIS / "check_lockfile_freshness.py")

CRATE_EXTENSION = "@@rules_rust+//crate_universe:extensions.bzl%crate"

GO_MOD = """module go.mindclade.dev

go 1.26.0

require (
\tconnectrpc.com/connect v1.18.1 // a trailing comment must not confuse the parser
\tgithub.com/lib/pq v1.12.3
)

require github.com/prometheus/client_golang v1.23.2 // indirect
"""

GO_SUM = """connectrpc.com/connect v1.18.1 h1:aaa=
connectrpc.com/connect v1.18.1/go.mod h1:bbb=
github.com/lib/pq v1.12.3 h1:ccc=
github.com/lib/pq v1.12.3/go.mod h1:ddd=
github.com/prometheus/client_golang v1.23.2 h1:eee=
github.com/prometheus/client_golang v1.23.2/go.mod h1:fff=
"""


def _digest(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def _write(root: Path, relative: str, text: str) -> None:
    path = root / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def _lock(recorded: list[str], *, version: int = 26) -> str:
    """A minimal `MODULE.bazel.lock` recording `recorded` as crate_universe inputs."""
    return json.dumps(
        {
            "lockFileVersion": version,
            "registryFileHashes": {},
            "selectedYankedVersions": {},
            "moduleExtensions": {
                CRATE_EXTENSION: {
                    "general": {
                        "bzlTransitiveDigest": "irrelevant",
                        "usagesDigest": "irrelevant",
                        "recordedInputs": recorded,
                        "generatedRepoSpecs": {},
                    }
                }
            },
            "facts": {},
        }
    )


@pytest.fixture
def tree(tmp_path: Path) -> Path:
    """A hermetic miniature of the repository: one member crate, both lockfiles, one Go module."""
    cargo_lock = "# This file is automatically @generated by Cargo.\nversion = 4\n"
    cargo_toml = '[workspace]\nresolver = "3"\nmembers = [\n    "libs/rust/faults",\n]\n'
    member = '[package]\nname = "mindclade_faults"\nversion = "0.0.0"\n'

    _write(tmp_path, "Cargo.lock", cargo_lock)
    _write(tmp_path, "Cargo.toml", cargo_toml)
    _write(tmp_path, "libs/rust/faults/Cargo.toml", member)
    _write(tmp_path, "go.mod", GO_MOD)
    _write(tmp_path, "go.sum", GO_SUM)
    _write(tmp_path, "sdk/go/go.mod", "module github.com/Mindclade/mindclade-go\n\ngo 1.23.2\n")
    _write(tmp_path, "sdk/go/go.sum", "")
    _write(
        tmp_path,
        "MODULE.bazel.lock",
        _lock(
            [
                "ENV:CARGO_BAZEL_REPIN \\0",
                "REPO_MAPPING:rules_rust+,bazel_skylib bazel_skylib+",
                f"FILE:@@//Cargo.lock {_digest(cargo_lock)}",
                f"FILE:@@//Cargo.toml {_digest(cargo_toml)}",
                f"FILE:@@//libs/rust/faults/Cargo.toml {_digest(member)}",
            ]
        ),
    )
    return tmp_path


def _errors(root: Path) -> str:
    return "\n".join(freshness.check(root))


def test_a_consistent_tree_passes(tree: Path) -> None:
    assert freshness.check(tree) == []


# --------------------------------------------------------------------------------------------
# The three live defect shapes.
