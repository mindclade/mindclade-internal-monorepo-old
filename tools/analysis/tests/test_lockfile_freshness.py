def test_edited_cargo_lock_is_reported(tree: Path) -> None:
    """PR #141 exactly: Cargo.lock moves, MODULE.bazel.lock does not."""
    (tree / "Cargo.lock").write_text("# edited\nversion = 4\n", encoding="utf-8")
    errors = _errors(tree)
    assert "Cargo.lock: changed since MODULE.bazel.lock was generated" in errors
    # The failure message must carry the fix, or a red CI run tells the author nothing.
    assert freshness.BAZEL_REPIN_COMMAND in errors
    assert "mod deps --lockfile_mode=update" in freshness.BAZEL_REPIN_COMMAND


def test_edited_member_manifest_is_reported(tree: Path) -> None:
    """A dependency edge added to a member crate invalidates the same extension."""
    (tree / "libs/rust/faults/Cargo.toml").write_text(
        '[package]\nname = "mindclade_faults"\n\n[dependencies]\nserde = "=1.0.0"\n',
        encoding="utf-8",
    )
    assert "libs/rust/faults/Cargo.toml: changed since MODULE.bazel.lock" in _errors(tree)


def test_added_workspace_member_is_reported(tree: Path) -> None:
    """The shape a digest comparison cannot see: a manifest the lock never recorded."""
    _write(tree, "libs/rust/newcomer/Cargo.toml", '[package]\nname = "mindclade_newcomer"\n')
    (tree / "Cargo.toml").write_text(
        '[workspace]\nmembers = [\n    "libs/rust/faults",\n    "libs/rust/newcomer",\n]\n',
        encoding="utf-8",
    )
    assert "libs/rust/newcomer/Cargo.toml: not recorded as a crate_universe input" in _errors(tree)


def test_added_member_via_a_glob_is_reported(tree: Path) -> None:
    """A glob member adds a crate with nobody editing a roster, so it is checked too."""
    _write(tree, "libs/rust/newcomer/Cargo.toml", '[package]\nname = "mindclade_newcomer"\n')
    (tree / "Cargo.toml").write_text(
        '[workspace]\nmembers = [\n    "libs/rust/*",\n]\n', encoding="utf-8"
    )
    assert "libs/rust/newcomer/Cargo.toml: not recorded as a crate_universe input" in _errors(tree)


def test_bumped_go_requirement_without_go_sum_is_reported(tree: Path) -> None:
    (tree / "go.mod").write_text(
        GO_MOD.replace("connectrpc.com/connect v1.18.1", "connectrpc.com/connect v1.18.2"),
        encoding="utf-8",
    )
    errors = _errors(tree)
    assert "go.sum does not authenticate connectrpc.com/connect v1.18.2" in errors
    assert freshness.GO_TIDY_COMMAND in errors


def test_go_sum_missing_only_the_go_mod_hash_is_reported(tree: Path) -> None:
    """The zip hash alone is not authentication; the go.mod hash is the one always required."""
    (tree / "go.sum").write_text(
        GO_SUM.replace("github.com/lib/pq v1.12.3/go.mod h1:ddd=\n", ""), encoding="utf-8"
    )
    assert "go.sum does not authenticate github.com/lib/pq v1.12.3" in _errors(tree)


